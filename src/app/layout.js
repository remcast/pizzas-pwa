import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import Link from "next/link";
import RegistrarSW from "./componentes/RegistrarSW";
import { createClient } from "./lib/supServer";
import { logout } from "./actions/authActions";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }) {
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();

  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        <header className="flex items-center justify-between gap-4 p-6 dark:bg-black w-full border-b border-b-stone-600">
          <div className="flex flex-grip items-center gap-4">
            <Link href='/'>INICIO </Link>
            <Link href='/producto'>PRODUCTOS </Link>
            <Link href='/contacto'>CONTACTANOS </Link>
          </div>
          <div className="flex flex-grip gap-4">
            {user ? (
              <>
                <span className="text-sm text-zinc-500">{user.email}</span>
                <form action={logout}>
                  <button type="submit">CERRAR SESIÓN</button>
                </form>
              </>
            ) : (
              <Link href='/login'>LOGIN</Link>
            )}
          </div>
        </header>
        <RegistrarSW />
        {children}
      </body>
    </html>
  );
}
